def spoken(t): return [re.sub(r"[^\w']", "", w).lower() for w in t.split() if re.sub(r"[^\w']", "", w)]
if __name__ == "__main__":
    script = open(os.path.join(P, "script_tts.txt")).read()
    assert [w for s in SCENES for w in spoken(s["line"])] == spoken(script), "lines do not cover the script"
    times = json.load(open("/tmp/claude-0/-home-user-Yuvraj-/8748aabc-52d5-5b71-a82b-6bad9d831f3a/scratchpad/chunks.json"))
    assert len(times) == len(SCENES), (len(times), len(SCENES))
    out, md = [], ["# WHO TF WORLD OWES TO? — image prompts", "",
                   f"{len(SCENES)} images. Generate each as **square 1:1**, name them `001.png`, `002.png` … in order.", ""]
    for i, (s, t) in enumerate(zip(SCENES, times), 1):
        assert s["line"] == t["line"], (i, s["line"], t["line"])
        name = f"{i:03d}.png"
        out.append({"image": name, "line": s["line"], "start": t["start"], "end": t["end"]})
        chars = " ".join(CHARACTERS[c] + "." for c in s["chars"])
        body = " ".join(x for x in [s["desc"][0].upper() + s["desc"][1:] + ".", chars, STYLE] if x)
        md += [f"## {i:03d} — \"{s['line']}\"", "", body, ""]
    json.dump(out, open(os.path.join(P, "scenes.json"), "w"), indent=1)
    open(os.path.join(P, "image_prompts.md"), "w").write("\n".join(md))
    print(len(SCENES), "scenes OK")
